#!/usr/bin/python3
# Exact 16 required corruption recipes. Run only after genuine own G4a freeze
# and cross-implementation fixture agreement. Never accepts science/benchmark DATA.
import os
import sys
import struct
import subprocess
import importlib.machinery
import importlib.util
sys.dont_write_bytecode = True

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    loader = importlib.machinery.SourceFileLoader('own_fixture',here+'/brs3_fixture')
    spec = importlib.util.spec_from_loader(loader.name,loader)
    f = importlib.util.module_from_spec(spec)
    loader.exec_module(f)
    try:
        argv = sys.argv[1:]
        f.check(len(argv) == 6 and set(argv[::2]) == {'--inputs','--data','--output'},'CLI',2,'argv')
        a = dict(zip(argv[::2],argv[1::2]))
        for key in ('--inputs','--data'):
            f.pathcheck(a[key])
        f.pathcheck(a['--output'],True)
        # Independently authenticate pristine data with actual full auditor before
        # any mutation. It must be fixture tier and have exactly one full chunk.
        os.mkdir(a['--output'],0o700)
        root, pristine = a['--output'],a['--data']
        f.check(set(os.listdir(pristine)) == {'chunk_000.bin','MANIFEST.json','MANIFEST.sha256'},'FORMAT',2,'data')
        original = {n:f.regular_read(pristine+'/'+n) for n in os.listdir(pristine)}
        f.manifest(original['MANIFEST.json'],'fixture-r1')
        f.check(len(original['chunk_000.bin']) == 64+16*f.RECORD,'FORMAT',2,'data')
        env = {'PATH':'/usr/bin:/bin','LANG':'C','LC_ALL':'C','PYTHONDONTWRITEBYTECODE':'1'}
        runs = []
        def audit(data,label,expect,code):
            result,report = root+'/'+label+'.results',root+'/'+label+'.audit'
            cmd = [here+'/brs3_audit','--inputs',a['--inputs'],'--tier','fixture-r1','--data',data,
                   '--results',result,'--report',report,'--threads','32']
            with open(root+'/'+label+'.stderr','xb') as err, open(root+'/'+label+'.stdout','xb') as out:
                rc = subprocess.call(cmd,cwd=root,env=env,stdin=subprocess.DEVNULL,stdout=out,stderr=err,close_fds=True)
            stderr = open(root+'/'+label+'.stderr','rb').read()
            ok = rc == expect and ((expect == 0 and os.path.isfile(result) and os.path.isfile(report)) or
                                   (expect != 0 and not os.path.lexists(result) and not os.path.lexists(report) and stderr.startswith(('BRS3_ERROR '+code+'\n').encode('ascii'))))
            evidence = {'id':label,'argv':cmd,'actual_exit':rc,'required_exit':expect,'required_code':code,
                        'stderr_sha256':f.digest(stderr),'check':ok}
            f.publish(root+'/'+label+'.receipt.json',f.canonical(evidence))
            runs.append(evidence)
            return ok
        f.check(audit(pristine,'pristine',0,''),'MISMATCH',3,'pristine')
        # Coherent forgery is generated by own RNG/operator, fixture keys only.
        forged = root+'/forgery_source'
        cmd = [here+'/brs3_fixture_stage','--inputs',a['--inputs'],'--output',forged,'--threads','32','--order','CA','--mode','forged']
        with open(root+'/forgery_generation.stderr','xb') as err, open(root+'/forgery_generation.stdout','xb') as out:
            rc = subprocess.call(cmd,cwd=root,env=env,stdin=subprocess.DEVNULL,stdout=out,stderr=err,close_fds=True)
        f.check(rc == 0,'MISMATCH',3,'forge_generation')
        forged_blob = f.regular_read(forged+'/chunk_000.bin')
        # Check exact unchanged scope: all other records, targets, S0..S255 and
        # history retry totals. Only x0 at S256 changes, all caches stay legal.
        o0 = original['chunk_000.bin'][64:64+f.RECORD]
        g0 = forged_blob[64:64+f.RECORD]
        f.check(forged_blob[64+f.RECORD:] == original['chunk_000.bin'][64+f.RECORD:] and
                g0[:69664] == o0[:69664] and g0[69668:69928] == o0[69668:69928] and
                g0[205096:206120] == o0[205096:206120] and
                int.from_bytes(g0[69664:69668],'little') == int.from_bytes(o0[69664:69668],'little') ^ 1,
                'MISMATCH',3,'forgery_scope')
        def repair(blobs, record_hash=False):
            blob = bytearray(blobs['chunk_000.bin'])
            if record_hash:
                base = 64
                blob[base+f.HASH_OFFSET:base+f.RECORD] = bytes.fromhex(f.digest(blob[base:base+f.HASH_OFFSET]))
            blobs['chunk_000.bin'] = bytes(blob)
            m = f.strict_json(blobs['MANIFEST.json'])
            m['files'][0]['sha256'] = f.digest(blob)
            blobs['MANIFEST.json'] = f.canonical(m)
            blobs['MANIFEST.sha256'] = (f.digest(blobs['MANIFEST.json'])+'  MANIFEST.json\n').encode('ascii')
        recipes = [('bitflip',3,'HASH'),('missing_chunk',2,'FORMAT'),('extra_file',2,'FORMAT'),
                    ('truncated_record',2,'FORMAT'),('reordered_records',2,'FORMAT'),('wrong_tier',2,'FORMAT'),
                    ('wrong_keys_hash',2,'FORMAT'),('wrong_protocol_hash',2,'FORMAT'),('wrong_contract_hash',2,'FORMAT'),
                    ('duplicate_block',2,'FORMAT'),('illegal_cache',3,'STATE'),('altered_endpoint_sum_rehashed',3,'MISMATCH'),
                    ('altered_retry_rehashed',3,'MISMATCH'),('altered_target_rehashed',3,'MISMATCH'),
                    ('altered_state_rehashed',3,'MISMATCH'),
                    ('self_consistent_forged_S256_recomputed_branches_sums_and_all_hashes',3,'MISMATCH')]
        all_ok = True
        for label, ex, code in recipes:
            blobs = dict(original)
            blob = bytearray(blobs['chunk_000.bin'])
            if label == 'bitflip':
                blob[96] ^= 1
                blobs['chunk_000.bin'] = bytes(blob)
            elif label == 'missing_chunk':
                del blobs['chunk_000.bin']
            elif label == 'extra_file':
                blobs['EXTRA.bin'] = b'\0'
            elif label == 'truncated_record':
                blobs['chunk_000.bin'] = bytes(blob[:-1])
            elif label in ('reordered_records','duplicate_block'):
                r0,r1 = bytes(blob[64:64+f.RECORD]),bytes(blob[64+f.RECORD:64+2*f.RECORD])
                blob[64:64+f.RECORD] = r1 if label == 'reordered_records' else r0
                blob[64+f.RECORD:64+2*f.RECORD] = r0
                blobs['chunk_000.bin'] = bytes(blob)
                repair(blobs)
            elif label == 'wrong_tier':
                blob[10] = 1
                blobs['chunk_000.bin'] = bytes(blob)
                repair(blobs)
            elif label.startswith('wrong_'):
                field = {'wrong_keys_hash':'keys_sha256','wrong_protocol_hash':'protocol_sha256','wrong_contract_hash':'contract_sha256'}[label]
                m = f.strict_json(blobs['MANIFEST.json'])
                m[field] = '0'*64
                blobs['MANIFEST.json'] = f.canonical(m)
                blobs['MANIFEST.sha256'] = (f.digest(blobs['MANIFEST.json'])+'  MANIFEST.json\n').encode('ascii')
            elif label == recipes[-1][0]:
                blobs['chunk_000.bin'] = forged_blob
                repair(blobs)
            else:
                if label == 'illegal_cache':
                    struct.pack_into('<I',blob,64+2208,1)
                elif label == 'altered_endpoint_sum_rehashed':
                    off = 64+208168
                    struct.pack_into('<I',blob,off,(struct.unpack_from('<I',blob,off)[0]+1) % 8193)
                elif label == 'altered_retry_rehashed':
                    off = 64+205096
                    struct.pack_into('<I',blob,off,(struct.unpack_from('<I',blob,off)[0]+1) % 8161)
                elif label == 'altered_target_rehashed':
                    blob[64+32] ^= 1
                elif label == 'altered_state_rehashed':
                    blob[64+2344] ^= 1
                blobs['chunk_000.bin'] = bytes(blob)
                repair(blobs,True)
            directory = root+'/'+label+'_DATA'
            os.mkdir(directory,0o700)
            for name,b in blobs.items():
                f.publish(directory+'/'+name,b)
            ok = audit(directory,label,ex,code)
            all_ok = all_ok and ok
        f.publish(root+'/CORRUPTION_REPORT.json',f.canonical({'schema':1,'required_cases':16,'actual_cases':len(runs)-1,'all_checks':all_ok,'runs':runs}))
        return 0 if all_ok else 3
    except f.Failure as e:
        sys.stderr.write('BRS3_ERROR '+e.code+'\n')
        return e.exit_code
    except Exception:
        sys.stderr.write('BRS3_ERROR IO\n')
        return 5
if __name__ == '__main__':
    sys.exit(main())
